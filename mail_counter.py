def check_day(Bg, f_in, f_out, f_cf, created_g, rejected, nsess, out_g):
    """Check rows for one day (SMTP in/out, content filter)."""
    types = collections.Counter(b["type"] for b in Bg)
    r = []
    if f_in:
        inb = [b for b in Bg if b["type"] == "INBOUND"]
        direct = sum(1 for b in inb if b["file"] in created_g)
        s = ("%d messages created by SMTP in %d sessions; %d INBOUND entries match directly, the other %d "
             "were rewritten (MDPGP) or came from other channels. %d recipients rejected (550)"
             % (len(created_g), nsess, direct, len(inb) - direct, sum(rejected.values())))
        if rejected:
            s += ": " + ", ".join("%s %d" % x for x in rejected.most_common(5))
        r.append(("SMTP in check", s))
    else:
        r.append(("SMTP in check", "file not found"))
    if f_out:
        ok = sum(1 for v in out_g.values() if v["ok"])
        r.append(("SMTP out check", "%d deliveries in the log, %d accepted by the receiving server; "
                  "REMOTE entries in the routing log: %d" % (len(out_g), ok, types["REMOTE"])))
    else:
        r.append(("SMTP out check", "file not found: external recipients taken from the To header"))
    if f_cf:
        cf = parse_content_filter(f_cf)
        outs = {num(b["file"]) for b in Bg if b["type"] != "INBOUND"} | \
               {num(b.get("path", "").split("\\")[-1]) for b in Bg if b["type"] == "INBOUND"}
        r.append(("Content filter check", "%d files processed, %d not in the routing log; "
                  "%d deleted by the filter" % (len(cf), sum(1 for k in cf if k not in outs),
                                                sum(1 for v in cf.values() if v["deleted"]))))
    else:
        r.append(("Content filter check", "file not found"))
    return types, r


def main():
    ap = argparse.ArgumentParser(description="Count sent and received mail per account from MDaemon logs")
    ap.add_argument("--folder", default=os.path.dirname(os.path.abspath(__file__)),
                    help="log folder (default: the script's folder)")
    ap.add_argument("--date", help="single day YYYY-MM-DD (default: latest day with a routing log)")
    ap.add_argument("--from", dest="date_from", help="range start YYYY-MM-DD (inclusive)")
    ap.add_argument("--to", dest="date_to", help="range end YYYY-MM-DD (inclusive)")
    ap.add_argument("--domain", help="internal domain, e.g. example.com (required unless set in mailboxes.txt)")
    ap.add_argument("--output", help="output Excel file")
    ap.add_argument("--aliases", help="aliases file (default: aliases.txt in the log folder or the script folder)")
    ap.add_argument("--mailboxes", help="mailbox folders file (default: mailboxes.txt, same lookup)")
    ap.add_argument("--log-names", metavar="FILE", help="log names per MDaemon language (default: log_names.txt, same lookup)")
    ap.add_argument("--all-log", action="store_true",
                    help="read only the MDaemon-YYYY-MM-DD-all.log file of each day and ignore the other logs; "
                         "the file can be very large, so its size is shown and a confirmation is asked")
    ap.add_argument("-y", "--yes", action="store_true", help="with --all-log: do not ask for confirmation")
    ap.add_argument("--draft-mailboxes", metavar="FILE",
                    help="write to FILE a draft mailboxes.txt inferred from the logs, to be reviewed")
    g = ap.add_argument_group("sheets", "extra Excel sheets (default: only 'Summary by account'); they can be combined")
    for flag, title in SHEET_FLAGS:
        g.add_argument(flag, dest="sh" + flag.replace("-", "_"), action="store_true", help='"%s" sheet' % title)
    g.add_argument("-a", dest="sh_all", action="store_true", help="all sheets")
    a = ap.parse_args()
    folder = a.folder

    def cfg_path(arg, name):
        if arg:
            if not os.path.isfile(arg):
                sys.exit("Configuration file not found: %s" % arg)
            return arg
        for d in (folder, os.path.dirname(os.path.abspath(__file__))):
            if os.path.isfile(os.path.join(d, name)):
                return os.path.join(d, name)
        return None
    f_alias, f_mbox = cfg_path(a.aliases, "aliases.txt"), cfg_path(a.mailboxes, "mailboxes.txt")
    f_names = cfg_path(a.log_names, "log_names.txt")
    if f_names:
        load_log_names(f_names)
    domain = a.domain
    if not domain and f_mbox:
        with open(f_mbox, encoding="utf-8-sig", errors="replace") as fc:
            for l in fc:
                k, _, v = l.partition("=")
                if k.strip().lower() == "domain":
                    domain = v.strip()
    if not domain:
        sys.exit("Set the internal domain with --domain example.com (or a 'domain = example.com' line in mailboxes.txt)")
    D = Domain(domain)

    def day(x, name):
        try:
            return datetime.date.fromisoformat(x)
        except ValueError:
            sys.exit("Invalid date for %s: %s (use the YYYY-MM-DD format)" % (name, x))

    idx, zips = index_logs(folder)
    main_kind = "all" if a.all_log else "routing"
    main_name = LOG_NAMES[main_kind][0]
    main_suffixes = tuple("-%s.log" % n.lower() for n in LOG_NAMES[main_kind])
    available = sorted(set(k[8:18] for k in idx if k.endswith(main_suffixes)))
    if a.date and (a.date_from or a.date_to):
        sys.exit("Use --date for one day or --from/--to for a range, not both.")
    if a.date:
        d_from = d_to = day(a.date, "--date")
    elif a.date_from or a.date_to:
        if not available and not (a.date_from and a.date_to):
            sys.exit("No MDaemon-*-%s.log file in %s" % (main_name, folder))
        d_from = day(a.date_from, "--from") if a.date_from else datetime.date.fromisoformat(available[0])
        d_to = day(a.date_to, "--to") if a.date_to else datetime.date.fromisoformat(available[-1])
        if d_to < d_from:
            sys.exit("--to (%s) is before --from (%s)" % (d_to, d_from))
    else:
        if not available:
            sys.exit("No MDaemon-*-%s.log file in %s" % (main_name, folder))
        d_from = d_to = datetime.date.fromisoformat(available[-1])
    requested = [(d_from + datetime.timedelta(days=i)).isoformat() for i in range((d_to - d_from).days + 1)]

    def find(date, kind):
        for name in LOG_NAMES[kind]:
            src = idx.get(("MDaemon-%s-%s.log" % (date, name)).lower())
            if src:
                return src

    if a.all_log:
        found = [f for f in (find(d, "all") for d in requested) if f]
        if found and not a.yes:
            print("WARNING: --all-log reads %d file(s), %.0f MB in total. This can take a while."
                  % (len(found), sum(src_size(f) for f in found) / 1e6))
            if not sys.stdin.isatty():
                sys.exit("Not running in a terminal: add -y (--yes) to confirm.")
            try:
                answer = input("Continue? [y/N] ")
            except EOFError:
                answer = ""
            if answer.strip().lower() not in ("y", "yes"):
                sys.exit("Cancelled, nothing done.")

    B, out, created, days, missing, per_day = [], {}, {}, [], [], []
    for d in requested:
        f_main = find(d, main_kind)
        if a.all_log:
            f_routing = f_out = f_in = f_cf = read_all_log(f_main) if f_main else None
        else:
            f_routing = f_main
        Bg = parse_routing(f_routing) if f_routing else []
        if not Bg:
            missing.append(d)
            continue
        if not a.all_log:
            f_out, f_in, f_cf = find(d, "smtp_out"), find(d, "smtp_in"), find(d, "content_filter")
        out_g = parse_smtp_out(f_out) if f_out else {}
        created_g, rejected, nsess = parse_smtp_in(f_in) if f_in else ({}, collections.Counter(), 0)
        types, chk = check_day(Bg, f_in, f_out, f_cf, created_g, rejected, nsess, out_g)
        per_day.append((d, src_name(f_main), types, chk))
        B += Bg
        out.update(out_g)
        created.update(created_g)
        days.append(d)
    if not days:
        if len(requested) == 1:
            sys.exit("MDaemon-%s-%s.log not found in %s: no logs for this day."
                     % (requested[0], main_name, folder))
        sys.exit("No routing log between %s and %s in %s." % (requested[0], requested[-1], folder))

    link(B)
    alias_cfg, mailbox_cfg = read_config(f_alias, D), read_config(f_mbox, D)
    account_of, folder2acc, mailboxes = map_mailboxes(B, created, D, alias_cfg, mailbox_cfg)
    if a.draft_mailboxes:
        paths = {}
        for b in B:
            if b["type"] == "LOCAL" and D.mailbox(b.get("path")):
                m = re.search(r"^(.*?users\\" + re.escape(D.dom) + r"\\[^\\]+)\\", b["path"], re.I)
                paths.setdefault(D.mailbox(b["path"]), m.group(1) if m else b["path"])
        with open(a.draft_mailboxes, "w", encoding="utf-8") as fd:
            fd.write("# Mailbox folders: one line per account, in the format\n"
                     "#    primary address = folder path on the server\n"
                     "# Draft inferred from the logs of %s: REVIEW before use.\n"
                     "domain = %s\n" % (", ".join(days), D.dom))
            for acc_, f, origin, *_ in sorted(mailboxes):
                fd.write("%s = %s\n" % (acc_, paths.get(f + D.at, "c:\\mdaemon\\users\\%s\\%s" % (D.dom, f))))
        print("Draft mailboxes file written to", a.draft_mailboxes)
    msgs = build_messages(B, out, D, account_of, folder2acc)
    acc, rows = count(msgs, D)

    tm = collections.Counter(m["kind"] for m in msgs)
    merged = sum(m["n_inbound"] - 1 for m in msgs if m["n_inbound"] > 1)
    deleted = [m for m in msgs if m["deleted"]]
    period = requested[0] if len(requested) == 1 else "from %s to %s" % (requested[0], requested[-1])
    sources = [
        ("Requested period", period),
        ("Period covered by the logs", "from %s to %s" % (B[0]["ts"], B[-1]["ts"])),
        ("Days without logs", ", ".join(missing) if missing else "none"),
        ("Folder", folder),
        ("Zip archives found", (", ".join(os.path.basename(z) for z in zips)
                                + " (logs read straight from the zip, nothing extracted to disk)")
         if zips else "none"),
        ("Days used for averages", "%d (%s): daily average = period total / %d"
         % (len(days), ", ".join(days), len(days))),
        ("Unique messages", "%d (%d normal, %d duplicates with the same Message-ID merged; %d MDaemon "
                            "notifications; %d auto-replies)" % (len(msgs), tm["normal"], merged,
                                                                 tm["MDaemon server notification"],
                                                                 tm["auto-reply"])),
    ]
    for d, name, types, chk in per_day:
        pre = "%s - " % d if len(days) > 1 else ""
        sources.append((pre + "Main source", "%s: %d INBOUND, %d LOCAL, %d REMOTE" % (
            name, types["INBOUND"], types["LOCAL"], types["REMOTE"])))
        sources += [(pre + k, v) for k, v in chk]
    if deleted:
        sources.append(("Messages not delivered", "; ".join("%s %s" % (m["ts"][:16], m["subj"]) for m in deleted)
                        + " - counted as sent, not as received"))
    not_cfg = [c for c in mailboxes if c[2] != "configuration"]
    with_notes = [c for c in mailboxes if c[5]]
    sources.append(("Configuration",
                    "aliases.txt: %s (%d aliases); mailboxes.txt: %s (%d mailboxes)" % (
                        f_alias or "not found", len(alias_cfg), f_mbox or "not found", len(mailbox_cfg))))
    sources.append(("Mailboxes and aliases",
                    "Aliases and folders come from the configuration; anything missing is inferred from the logs "
                    "(messages with a single recipient in the SMTP in log and their delivery folder). %d folders "
                    "not configured, %d with notes or conflicts: see the 'Mailboxes and aliases' sheet. Aliases "
                    "are counted under their primary account." % (len(not_cfg), len(with_notes))))
    sources.append(("Counting rules",
                    "Sent = messages whose sender is @%s, each counted once even with several recipients. "
                    "'With external recipients' = at least one recipient outside the domain. Received = "
                    "messages delivered to the mailbox, once per mailbox. A message to oneself counts as sent "
                    "and received. Auto-replies and server notifications are kept apart. With a date range, "
                    "each message belongs to the day it entered the server." % D.dom))

    suffix = requested[0] if len(requested) == 1 else "%s_%s" % (requested[0], requested[-1])
    out_path = a.output or os.path.join(folder, "mail_count_%s_%s.xlsx" % (D.dom.split(".")[0], suffix))
    sheets = None if a.sh_all else {t for f, t in SHEET_FLAGS if getattr(a, "sh" + f.replace("-", "_"))}
    accounts, keys = write_excel(out_path, acc, rows, msgs, D, sources, mailboxes, days, sheets)

    tot = collections.Counter()
    for x in accounts:
        tot.update(acc[x])
    print("Period %s - days with logs: %s - %d unique messages, %d accounts"
          % (period, ", ".join(days), len(msgs), len(accounts)))
    if missing:
        print("WARNING, days without logs: %s" % ", ".join(missing))
    print("Configuration: %d aliases (%s), %d mailboxes (%s)" % (
        len(alias_cfg), f_alias or "aliases.txt not found", len(mailbox_cfg), f_mbox or "mailboxes.txt not found"))
    if not_cfg or with_notes:
        print("WARNING: %d folders not configured, %d with notes: see the 'Mailboxes and aliases' sheet%s"
              % (len(not_cfg), len(with_notes), "" if sheets is None or "Mailboxes and aliases" in sheets
                 else " (add -mb to include it)"))
    if sheets is not None and len(days) == 1 and "By day" in sheets:
        print("NOTE: the 'By day' sheet is only written for more than one day")
    print("Sent %d (internal only %d, with external %d) | Received %d (from internal %d, from external %d, "
          "notifications %d)" % (tot["sent"], tot["sent_int"], tot["sent_ext"], tot["rx"], tot["rx_int"],
                                 tot["rx_ext"], tot["rx_sys"]))
    for d, name, types, chk in per_day:
        for k, v in chk:
            print(" - %s %s: %s" % (d, k, v))
    print()
    print("%-34s %8s %8s %8s %10s" % ("Account", "Sent", "external", "Received", "from ext."))
    for x in accounts[:15]:
        print("%-34s %8d %8d %8d %10d" % (x, acc[x]["sent"], acc[x]["sent_ext"], acc[x]["rx"], acc[x]["rx_ext"]))
    print("\nExcel file:", out_path)


if __name__ == "__main__":
    main()
