# ---------------------------------------------------------------- helpers
def read_lines(src):
    """Read a log: src is a path or (zip file, member name). Zip members are read in memory,
    nothing is extracted to disk. A list is returned as it is (lines already read by read_all_log)."""
    if isinstance(src, list):
        return src
    if isinstance(src, tuple):
        with zipfile.ZipFile(src[0]) as z, z.open(src[1]) as f:
            return f.read().decode(ENC, errors="replace").splitlines()
    with open(src, encoding=ENC, errors="replace") as f:
        return f.read().splitlines()


def src_size(src):
    if isinstance(src, tuple):
        with zipfile.ZipFile(src[0]) as z:
            return z.getinfo(src[1]).file_size
    return os.path.getsize(src)


def read_all_log(src):
    """Read an all.log (path or zip member) in chunks and return only the lines the parsers use:
    the file can be hundreds of MB, almost all of it IMAP traffic."""
    keep = re.compile("|".join([
        r": (?:INBOUND|LOCAL|REMOTE) message: ", r": \*  (?:[A-Za-z\- ]+:|Session )", r": -{9}",   # routing
        r"RCPT T[Oo]:", r"MAIL FROM:", r"(?:-->|<--) [25]50 ",                        # SMTP in and out
        r": Session \d+; child", r"Accepting SMTP connection",
        r"Content Filter processing", r"Message deleted", r"\* Message subject:",    # content filter
    ] + [re.escape(p) for p in MESSAGE_CREATED]).encode(ENC))
    lines, tail = [], b""
    z = zipfile.ZipFile(src[0]) if isinstance(src, tuple) else None
    with (z.open(src[1]) if z else open(src, "rb")) as f:
        while True:
            chunk = f.read(1 << 24)
            if not chunk:
                break
            parts = (tail + chunk).split(b"\n")
            tail = parts.pop()
            lines += [l for l in parts if keep.search(l)]
    if z:
        z.close()
    if keep.search(tail):
        lines.append(tail)
    return [l.decode(ENC, errors="replace").rstrip("\r") for l in lines]


def src_name(src):
    if isinstance(src, tuple):
        return "%s (inside %s)" % (os.path.basename(src[1]), os.path.basename(src[0]))
    return os.path.basename(src)


def load_log_names(path):
    """Add to LOG_NAMES and MESSAGE_CREATED the names of every language section of log_names.txt."""
    cp = configparser.ConfigParser(interpolation=None)
    try:
        with open(path, encoding="utf-8-sig") as f:
            cp.read_file(f)
    except configparser.Error as e:
        sys.exit("Invalid %s: %s" % (path, e))
    for section in cp.sections():
        for key, value in cp.items(section):
            target = MESSAGE_CREATED if key == "message_created" else LOG_NAMES.get(key)
            if target is None:
                sys.exit("Unknown key '%s' in section [%s] of %s" % (key, section, path))
            target += [n.strip() for n in value.split(",") if n.strip() and n.strip() not in target]


def index_logs(folder):
    """Log name -> source. Looks for loose .log files and for logs inside .zip files (also in
    subfolders). A loose log wins over a zipped one; among zips, the largest copy wins."""
    idx, size, zips = {}, {}, []
    for p in sorted(glob.glob(os.path.join(folder, "**", "*.zip"), recursive=True)):
        try:
            with zipfile.ZipFile(p) as z:
                for zi in z.infolist():
                    b = zi.filename.replace("\\", "/").split("/")[-1]
                    if re.match(r"MDaemon-\d{4}-\d\d-\d\d-.*\.log$", b, re.I):
                        # the same log can be in two zips (one with the header only): keep the largest
                        if b.lower() not in idx or zi.file_size > size[b.lower()]:
                            idx[b.lower()], size[b.lower()] = (p, zi.filename), zi.file_size
            zips.append(p)
        except zipfile.BadZipFile:
            print("WARNING: %s is not a valid zip file, skipped" % p)
    for p in glob.glob(os.path.join(folder, "**", "MDaemon-*.log"), recursive=True):
        idx[os.path.basename(p).lower()] = p
    return idx, zips


def num(fn):
    """Queue file sequence number without prefix (md35N / pd35N -> N)."""
    m = re.match(r"[a-z]+(\d+)", fn or "")
    return m.group(1)[2:] if m else None


def addrs(s):
    return [a.lower().strip("'.") for a in re.findall(r"[\w.+\-=&']+@[\w\-]+(?:\.[\w\-]+)+", s or "")]


def addr(s):
    a = addrs(s)
    return a[-1] if a else (s or "").strip().lower()


class Domain:
    def __init__(self, dom):
        self.dom = dom.lower().lstrip("@")
        self.at = "@" + self.dom
        self._sub = re.compile(r"@[\w.\-]*" + re.escape(self.dom) + r"$")

    def internal(self, a):
        return a.endswith(self.at) or a.endswith("." + self.dom)

    def norm(self, a):
        return self._sub.sub(self.at, a) if self.internal(a) else a

    def mailbox(self, path):
        m = re.search(r"users\\" + re.escape(self.dom) + r"\\([^\\]+)\\", path or "", re.I)
        return (m.group(1).lower().split("@")[0] + self.at) if m else None


# ---------------------------------------------------------------- parsing
def parse_routing(path):
    pat = re.compile(r"^\w+ (\d{4}-\d\d-\d\d \d\d:\d\d:\d\d)\.\d+: (?:\d+: )?(.*)$")
    blocks, cur, remote = [], None, set()
    for l in read_lines(path):
        m = pat.match(l)
        if not m:
            continue
        ts, body = m.groups()
        mm = re.match(r"(INBOUND|LOCAL|REMOTE) message: (\S+)", body)
        if mm:
            cur = {"ts": ts, "type": mm.group(1), "file": mm.group(2), "From": "", "To": "",
                   "Subject": "", "Message-ID": ""}
            blocks.append(cur)
            continue
        if body.startswith("----------"):
            cur = None
            continue
        if cur is None:
            continue
        mm = re.match(r"\*  Session (\d+);", body)
        if mm:
            # all.log: the same REMOTE entry is also the header of the SMTP out transcript
            if (cur["file"], mm.group(1)) in remote:
                blocks.pop()
                cur = None
            else:
                remote.add((cur["file"], mm.group(1)))
            continue
        mm = re.match(r"\*  ([A-Za-z\- ]+): ?(.*)$", body)
        if mm:
            k, v = mm.groups()
            if k == "Size":
                s, _, p = v.partition("; ")
                cur["path"] = p.strip("<>")
            else:
                cur[k] = v
    return blocks


def parse_smtp_out(path):
    out = collections.defaultdict(lambda: {"rcpt": [], "ok": False})
    cur = None
    for l in read_lines(path):
        m = re.search(r"REMOTE message: (\S+)", l)
        if m:
            cur = num(m.group(1))
            out[cur]
            continue
        if cur is None:
            continue
        m = re.search(r"--> RCPT To:<([^>]*)>", l)
        if m:
            out[cur]["rcpt"].append(m.group(1).lower())
        if re.search(r"<-- 250 2\.6\.0|<-- 250 .*queued|<-- 250 OK", l, re.I):
            out[cur]["ok"] = True
    return dict(out)


def parse_smtp_in(path):
    created, rejected, sess, nsess = {}, collections.Counter(), None, 0
    created_re = re.compile(r"(?:%s): (\S+)" % "|".join(map(re.escape, MESSAGE_CREATED)))
    for l in read_lines(path):
        if re.search(r": Session \d+; child", l):
            sess = {"rcpt": [], "from": None, "pending": None}
            continue
        if sess is None:
            continue
        if "Accepting SMTP connection" in l:
            nsess += 1
        m = re.search(r"<-- MAIL FROM:\s*<([^>]*)>", l, re.I)
        if m:
            sess["from"] = m.group(1).lower()
        m = re.search(r"<-- RCPT TO:\s*<([^>]*)>", l, re.I)
        if m:
            sess["pending"] = m.group(1).lower()
        if "250 2.1.5" in l and sess["pending"]:
            sess["rcpt"].append(sess["pending"])
            sess["pending"] = None
        m = re.search(r"--> 550 5\.1\.1 Recipient unknown <([^>]*)>", l)
        if m:
            rejected[m.group(1).lower()] += 1
        m = created_re.search(l)
        if m:
            created[m.group(1).split("\\")[-1]] = {"from": sess["from"], "rcpt": list(sess["rcpt"])}
            sess["rcpt"] = []
    return created, rejected, nsess


def parse_content_filter(path):
    cf, c = {}, None
    for l in read_lines(path):
        m = re.search(r"Content Filter processing (\S+?)\.\.\.", l)
        if m:
            c = {"deleted": False}
            cf[num(m.group(1).split("\\")[-1])] = c
            continue
        if c is None:
            continue
        if "Message deleted" in l:
            c["deleted"] = True
        m = re.search(r"\* Message subject: (.*)", l)
        if m:
            c["subject"] = m.group(1).strip()
    return cf


# ---------------------------------------------------------------- analysis
def link(B):
    def key(b):
        return (addr(b["From"]), b["Subject"].strip(), b["Message-ID"].strip())
    byq = {}
    for i, b in enumerate(B):
        b["i"] = i
        if b["type"] == "INBOUND":
            byq[num(b.get("path", "").split("\\")[-1])] = b
    last = {}
    for b in B:
        if b["type"] == "INBOUND":
            last[key(b)] = b
            b["outs"] = []
            b["parent"] = None
            continue
        p = byq.get(num(b["file"]))
        if p is None or key(p) != key(b):
            p = last.get(key(b)) or p
        b["parent"] = p["i"] if p else None
        if p:
            p["outs"].append(b["i"])


def read_config(path, D):
    """'key = value' lines (blank lines and # ignored). Returns {key: value}."""
    cfg = {}
    if not path or not os.path.isfile(path):
        return cfg
    with open(path, encoding="utf-8-sig", errors="replace") as f:
        for n, l in enumerate(f, 1):
            l = l.strip()
            if not l or l.startswith("#"):
                continue
            if "=" not in l:
                print("WARNING: %s line %d ignored (missing '='): %s" % (os.path.basename(path), n, l))
                continue
            k, v = (x.strip() for x in l.split("=", 1))
            if k.lower() == "domain":
                continue
            cfg[D.norm(k.lower())] = v
    return cfg


def folder_from_path(v, D):
    """'c:\\MDaemon\\Users\\example.com\\mario' -> folder key as returned by D.mailbox()."""
    seg = [x for x in re.split(r"[\\/]+", v.strip().strip('"')) if x]
    return (seg[-1].lower().split("@")[0] + D.at) if seg else None


def map_mailboxes(B, created, D, alias_cfg=None, mailbox_cfg=None):
    """Link addresses and aliases to the real mailbox folders.

    Configuration comes first (aliases.txt: alias = primary; mailboxes.txt: primary = folder).
    Anything not configured is inferred from the logs: messages with a single internal recipient
    (RCPT lines of the SMTP in log) and the folder they are delivered to.
    Returns (address -> account function, folder -> account, rows for the Mailboxes and aliases sheet).
    """
    alias_cfg = {k: D.norm(v.lower()) for k, v in (alias_cfg or {}).items()}
    mailbox_cfg = mailbox_cfg or {}

    def resolve_cfg(a):
        seen = set()
        while a in alias_cfg and a not in seen:
            seen.add(a)
            a = alias_cfg[a]
        return a

    folder_cfg = {}  # folder -> primary (from configuration)
    for prim, path in mailbox_cfg.items():
        f = folder_from_path(path, D)
        if f:
            folder_cfg[f] = resolve_cfg(prim)

    # inference from the logs
    pairs = collections.defaultdict(collections.Counter)
    tot = collections.Counter()
    for b in B:
        if b["type"] != "INBOUND" or b["file"] not in created:
            continue
        rc = set(D.norm(r) for r in created[b["file"]]["rcpt"] if D.internal(r))
        if len(rc) != 1:
            continue
        r = rc.pop()
        tot[r] += 1
        for f in set(D.mailbox(B[i].get("path")) for i in b["outs"] if B[i]["type"] == "LOCAL"):
            if f:
                pairs[r][f] += 1
    addr2folder = {}
    for r, c in pairs.items():
        home = [f for f, n in c.items() if n >= 0.9 * tot[r]]
        if len(home) == 1:  # several folders at 100% = distribution list, not mapped
            addr2folder[r] = home[0]

    notes = collections.defaultdict(list)
    folder2acc = dict(folder_cfg)
    per_folder = collections.defaultdict(list)
    for r, f in addr2folder.items():
        per_folder[f].append(r)
    for f, rs in per_folder.items():
        if f in folder_cfg:
            continue
        prim = sorted(set(resolve_cfg(r) for r in rs))
        same = [r for r in prim if r.split("@")[0] == f.split("@")[0]]
        folder2acc[f] = same[0] if same else max(prim, key=lambda r: (tot[r], r))
    acc2folder = {}
    for f, acc in folder2acc.items():
        acc2folder.setdefault(acc, f)

    # conflicts between configuration and logs
    for r, f in sorted(addr2folder.items()):
        expected = resolve_cfg(r)
        configured = r in alias_cfg or expected in acc2folder and acc2folder[expected] in folder_cfg
        if configured and folder2acc.get(f) != expected:
            notes[f].append("according to the logs %s is delivered to this folder, but the configuration "
                            "assigns it to %s" % (r, expected))

    def account_of(a):
        a = D.norm(a.lower())
        if a in alias_cfg:
            return resolve_cfg(a)
        if a in addr2folder:
            return folder2acc[addr2folder[a]]
        return a

    info = []
    all_folders = set(folder2acc) | {D.mailbox(b.get("path")) for b in B if b["type"] == "LOCAL"} - {None}
    for f in sorted(all_folders):
        acc = folder2acc.get(f, f)
        a_cfg = sorted(k for k in alias_cfg if resolve_cfg(k) == acc)
        a_log = sorted(r for r, ff in addr2folder.items() if ff == f and r != acc and r not in alias_cfg)
        if f in folder_cfg:
            origin = "configuration"
        else:
            origin = "inferred from logs (not in mailboxes.txt)"
            if a_log:
                notes[f].append("aliases inferred from the logs, not in aliases.txt")
        info.append((acc, f.split("@")[0], origin, ", ".join(a_cfg), ", ".join(a_log), "; ".join(notes[f])))
    return account_of, folder2acc, info


def build_messages(B, out, D, account_of=None, folder2acc=None):
    folder2acc = folder2acc or {}

    def acc_of(a):
        return account_of(a) if account_of else D.norm(a)
    msgs, bymid = [], {}

    def new(b, origin):
        f = addr(b["From"])
        m = dict(ts=b["ts"], frm=acc_of(f), from_raw=b["From"], to_hdr=b["To"], subj=b["Subject"],
                 mid=b["Message-ID"].strip(), origin=origin, local=[], remote=[], fwd=[],
                 deleted=False, n_inbound=0)
        msgs.append(m)
        return m

    for b in B:
        if b["type"] != "INBOUND":
            continue
        k = (b["Message-ID"].strip(), addr(b["From"]))
        if k[0] and k in bymid:
            m = bymid[k]
        else:
            m = new(b, "inbound")
            if k[0]:
                bymid[k] = m
        m["n_inbound"] += 1
        b["msg"] = m
        if not b["outs"]:
            m["deleted"] = True
    for b in B:
        if b["type"] == "INBOUND":
            continue
        if b["parent"] is not None:
            m = B[b["parent"]]["msg"]
        else:
            k = ("gen", b["Message-ID"].strip(), addr(b["From"]))
            if k[1] and k in bymid:
                m = bymid[k]
            else:
                m = new(b, "generated by the server (" + b["file"][:4] + ")")
                if k[1]:
                    bymid[k] = m
        if b["type"] == "LOCAL":
            mb = D.mailbox(b.get("path"))
            if mb:
                mb = folder2acc.get(mb, mb)
            else:
                t = addrs(b["To"])
                mb = acc_of(t[0]) if t and D.internal(t[0]) else None
            if mb:
                m["local"].append(mb)
        else:
            rc = out.get(num(b["file"]), {}).get("rcpt") or addrs(b["To"])
            if "Forwarded from" in b:
                m["fwd"].append((acc_of(addr(b["Forwarded from"])), rc))
            else:
                m["remote"] += [acc_of(r) for r in rc]
    for m in msgs:
        f = m["frm"]
        if f.startswith("mdaemon@"):
            m["kind"] = "MDaemon server notification"
        elif m["origin"].startswith("generated") and D.internal(f):
            m["kind"] = "auto-reply"
        else:
            m["kind"] = "normal"
        if m["deleted"]:
            h = [acc_of(a) for a in addrs(m["to_hdr"])]
            m["ints"] = sorted(set(a for a in h if D.internal(a)))
            m["exts"] = sorted(set(a for a in h if not D.internal(a)))
        else:
            m["exts"] = sorted(set(r for r in m["remote"] if not D.internal(r)))
            m["ints"] = sorted(set(m["local"]) | set(r for r in m["remote"] if D.internal(r)))
    return msgs


def count(msgs, D):
    acc = collections.defaultdict(collections.Counter)
    rows = []
    for m in msgs:
        f = m["frm"]
        if D.internal(f) and m["kind"] != "MDaemon server notification":
            if m["kind"] == "auto-reply":
                acc[f]["auto"] += 1
                rows.append((f, "Auto-reply sent", m))
            else:
                acc[f]["sent"] += 1
                acc[f]["sent_ext" if m["exts"] else "sent_int"] += 1
                acc[f]["n_ext_rcpt"] += len(m["exts"])
                rows.append((f, "Sent", m))
        for fw, rc in m["fwd"]:
            acc[fw]["fwd"] += 1
        if m["deleted"]:
            continue
        for mb in sorted(set(m["local"])):
            if m["kind"] == "MDaemon server notification":
                acc[mb]["rx_sys"] += 1
                k = "Received (server notification)"
            elif D.internal(f):
                acc[mb]["rx_int"] += 1
                k = "Received from internal"
            else:
                acc[mb]["rx_ext"] += 1
                k = "Received from external"
            acc[mb]["rx"] += 1
            rows.append((mb, k, m))
    return acc, rows


# ---------------------------------------------------------------- excel
def put(ws, r, c, v):
    """Write a cell. Text always stays text: a subject starting with '=' (e.g. =?utf-8?...) must
    not become a formula, and control characters Excel does not accept are removed."""
    if isinstance(v, str):
        v = ILLEGAL_CHARACTERS_RE.sub("", v)
        cell = ws.cell(r, c)
        cell.value = v
        cell.data_type = "s"
        return cell
    return ws.cell(r, c, v)


def write_excel(path, acc, rows, msgs, D, sources, mailboxes, days, sheets=None):
    """sheets: titles of the extra sheets to keep (None = all); the summary is always written."""
    wb = Workbook()
    H = Font(bold=True, color="FFFFFF")
    HF = PatternFill("solid", fgColor="1F4E78")
    TF = PatternFill("solid", fgColor="D9E1F2")

    def header(ws, cols):
        for i, c in enumerate(cols, 1):
            x = ws.cell(1, i, c)
            x.font, x.fill = H, HF
            x.alignment = Alignment(wrap_text=True, vertical="center")
        ws.freeze_panes = ws.cell(2, 1)

    def widths(ws, w):
        for i, x in enumerate(w, 1):
            ws.column_dimensions[get_column_letter(i)].width = x

    accounts = sorted(acc, key=lambda a: (-(acc[a]["sent"] + acc[a]["rx"]), a))
    ws = wb.active
    ws.title = "Summary by account"
    cols = ["Account", "Sent (total)", "Sent to internal only", "Sent with external recipients",
            "No. of external recipients", "Auto-replies sent", "Received (total)",
            "Received from internal", "Received from external", "MDaemon notifications received",
            "Automatic forwards to external", "Daily average sent", "Daily average received"]
    keys = ["sent", "sent_int", "sent_ext", "n_ext_rcpt", "auto", "rx", "rx_int", "rx_ext", "rx_sys", "fwd"]
    header(ws, cols)
    for r, a in enumerate(accounts, 2):
        put(ws, r, 1, a)
        for j, k in enumerate(keys, 2):
            ws.cell(r, j, acc[a][k])
        ws.cell(r, len(keys) + 2, round(acc[a]["sent"] / len(days), 1))
        ws.cell(r, len(keys) + 3, round(acc[a]["rx"] / len(days), 1))
    n = len(accounts) + 1
    t = n + 1
    ws.cell(t, 1, "TOTAL").font = Font(bold=True)
    for j in range(2, len(cols) + 1):
        L = get_column_letter(j)
        ws.cell(t, j, "=SUM(%s2:%s%d)" % (L, L, n)).font = Font(bold=True)
    for j in range(1, len(cols) + 1):
        ws.cell(t, j).fill = TF
    ws.row_dimensions[1].height = 45
    widths(ws, [34] + [14] * 12)
    ws.auto_filter.ref = "A1:%s%d" % (get_column_letter(len(cols)), n)

    if len(days) > 1:
        g = collections.defaultdict(collections.Counter)
        for x, k, m in rows:
            d = m["ts"][:10]
            if k == "Sent":
                g[x][(d, "s")] += 1
            elif k.startswith("Received"):
                g[x][(d, "r")] += 1
        wsg = wb.create_sheet("By day")
        cg = ["Account"]
        for d in days:
            cg += ["%s sent" % d, "%s received" % d]
        header(wsg, cg)
        for r, x in enumerate(accounts, 2):
            put(wsg, r, 1, x)
            for j, d in enumerate(days):
                wsg.cell(r, 2 + 2 * j, g[x][(d, "s")])
                wsg.cell(r, 3 + 2 * j, g[x][(d, "r")])
        wsg.cell(t, 1, "TOTAL").font = Font(bold=True)
        for j in range(2, len(cg) + 1):
            L = get_column_letter(j)
            wsg.cell(t, j, "=SUM(%s2:%s%d)" % (L, L, n)).font = Font(bold=True)
            wsg.cell(t, j).fill = TF
        wsg.cell(t, 1).fill = TF
        wsg.row_dimensions[1].height = 30
        widths(wsg, [34] + [12] * (len(cg) - 1))

    ws2 = wb.create_sheet("Message detail")
    header(ws2, ["Date/time", "Kind", "Direction", "Sender", "Internal recipients (mailboxes)",
                 "External recipients", "Subject", "Message-ID", "Notes"])
    for r, m in enumerate(sorted(msgs, key=lambda m: m["ts"]), 2):
        if D.internal(m["frm"]):
            direction = "Sent to external" if m["exts"] else "Internal"
        else:
            direction = "Received from external"
        notes = []
        if m["deleted"]:
            notes.append("Deleted by the content filter (not delivered)")
        if m["n_inbound"] > 1:
            notes.append("Received %d times with the same Message-ID: counted once" % m["n_inbound"])
        for fw, rc in m["fwd"]:
            notes.append("Automatic forward from %s to %s" % (fw, ", ".join(rc)))
        vals = [m["ts"], m["kind"], direction, m["from_raw"], ", ".join(m["ints"]), ", ".join(m["exts"]),
                m["subj"], m["mid"], "; ".join(notes)]
        for j, v in enumerate(vals, 1):
            put(ws2, r, j, v)
    widths(ws2, [19, 24, 22, 40, 45, 45, 60, 40, 40])
    ws2.auto_filter.ref = "A1:I%d" % (len(msgs) + 1)

    ws3 = wb.create_sheet("Detail by account")
    header(ws3, ["Account", "Movement", "Date/time", "Sender", "Internal recipients (mailboxes)",
                 "External recipients", "Subject"])
    for r, (a, k, m) in enumerate(sorted(rows, key=lambda x: (x[0], x[1], x[2]["ts"])), 2):
        for j, v in enumerate([a, k, m["ts"], m["from_raw"], ", ".join(m["ints"]), ", ".join(m["exts"]),
                               m["subj"]], 1):
            put(ws3, r, j, v)
    widths(ws3, [32, 30, 19, 40, 45, 45, 60])
    ws3.auto_filter.ref = "A1:G%d" % (len(rows) + 1)

    ws5 = wb.create_sheet("Mailboxes and aliases")
    header(ws5, ["Account", "Mailbox folder on the server", "Origin", "Aliases from aliases.txt",
                 "Other addresses inferred from logs", "Notes"])
    for r, row in enumerate(mailboxes, 2):
        for j, v in enumerate(row, 1):
            put(ws5, r, j, v)
    widths(ws5, [34, 24, 34, 60, 45, 70])

    ws4 = wb.create_sheet("Sources and checks")
    header(ws4, ["Item", "Detail"])
    for r, (a, b) in enumerate(sources, 2):
        put(ws4, r, 1, a).font = Font(bold=True)
        put(ws4, r, 2, b).alignment = Alignment(wrap_text=True, vertical="top")
    widths(ws4, [28, 120])
    for w in wb.worksheets[1:]:
        if sheets is not None and w.title not in sheets:
            wb.remove(w)
    wb.save(path)
    return accounts, keys


