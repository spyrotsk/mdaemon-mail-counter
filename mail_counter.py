#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
mail_counter.py - Count sent and received mail per account from MDaemon logs.

USAGE (from a command prompt, in the log folder):
    python mail_counter.py --domain example.com                          -> latest day found
    python mail_counter.py --domain example.com --date 2026-01-15        -> one day
    python mail_counter.py --domain example.com --from 2026-01-10 --to 2026-01-15   -> date range
    python mail_counter.py --domain example.com --from 2026-01-10        -> up to the latest day found
    python mail_counter.py --domain example.com --folder "D:\\logs" --output count.xlsx
  The internal domain is required: --domain, or a "domain = example.com" line in mailboxes.txt.

ZIP ARCHIVES: you can leave the MDaemon log archives in the folder as they are
  (e.g. Logs-YYYY-MM-DD-Ddd-hh-mm-ss.zip). The script finds them, also in subfolders, and reads
  the 4 logs it needs straight from the zip, in memory. Nothing is extracted to disk and the zips
  are left untouched. If the same log is both loose and inside a zip, the loose file wins; if it is
  in several zips, the largest copy wins.

CONFIGURATION (text files next to the script or in the log folder; blank lines and # are ignored):
  aliases.txt    one line per alias:            alias@example.com = primary@example.com
  mailboxes.txt  one line per real mailbox:     primary@example.com = c:\\MDaemon\\Users\\example.com\\folder
  Aliases point to the primary address and therefore to its mailbox folder; mailboxes.txt only lists
  primary addresses. Anything not configured is inferred from the logs and reported in the
  "Mailboxes and aliases" sheet, together with any conflict between configuration and logs.
  Full examples: aliases.example.txt and mailboxes.example.txt.
  Other file names:  --aliases FILE  --mailboxes FILE
  To create a draft mailboxes.txt from the logs:  python mail_counter.py --domain example.com --draft-mailboxes mailboxes.txt

REQUIREMENTS: Python 3.8+ and openpyxl  (once:  python -m pip install openpyxl)

LOGS READ (for each selected day, in the given folder and its subfolders):
    MDaemon-YYYY-MM-DD-Routing.log            main source (required)
    MDaemon-YYYY-MM-DD-SMTP-out.log           real external recipients + delivery check
    MDaemon-YYYY-MM-DD-SMTP-in.log            inbound check, rejected recipients
    MDaemon-YYYY-MM-DD-Content-Filter.log     check + messages deleted by the filter (optional)
  These are the names written by an English MDaemon. The names used by the other MDaemon
  languages are read from log_names.txt (next to the script or in the log folder; another
  file with --log-names FILE): if your logs are not found, add their names there.
  Missing files (except the routing log) are skipped and reported. Days in the range without a
  routing log are listed on screen and in the "Sources and checks" sheet.

SINGLE LOG (--all-log): reads only MDaemon-YYYY-MM-DD-all.log, the log where MDaemon writes
  everything, and ignores the other logs. That file can be hundreds of MB (it also holds all the
  IMAP traffic): the script shows its size and asks for confirmation before reading it
  (-y / --yes to skip the question). It is read in chunks, also from inside a zip.

METHOD:
  - Unique message = each INBOUND entry of the routing log; INBOUND entries with the same
    Message-ID and the same sender are merged (counted once). Messages generated by the server
    without an INBOUND entry (pd75/pd25 queues: notifications, reminders, auto-replies) are
    separate messages.
  - Each LOCAL/REMOTE delivery is linked to its INBOUND entry (queue file number, or
    sender+subject+Message-ID).
  - Sent = messages whose sender is @domain (MDaemon notifications excluded, auto-replies kept
    apart). "With external recipients" = at least one recipient outside the domain, taken from
    the RCPT lines of the SMTP out log.
  - Received = LOCAL deliveries into the mailbox (folder c:\\mdaemon\\users\\<domain>\\<mailbox>),
    once per message and mailbox; split into from internal / from external / server notifications.
  - Messages deleted by the content filter: counted as sent, not as received.
  - With a date range all days are analysed together: a message that entered at 23:59 and was
    delivered at 00:00 the next day stays one message, counted on the day it entered; the same
    Message-ID received on different days is counted once.

SHEETS: by default the Excel file only has the "Summary by account" sheet. Add the others with
  -d (By day)  -md (Message detail)  -ad (Detail by account)  -mb (Mailboxes and aliases)
  -s (Sources and checks)  -a (all), e.g.:  python mail_counter.py --domain example.com -d -md

OUTPUT: mail_count_<domain-first-label>_YYYY-MM-DD.xlsx (one day) or
  mail_count_<domain-first-label>_<from>_<to>.xlsx (range) in the log folder, with the sheets
  Summary by account (whole period, with daily averages over the days that have logs) / By day /
  Message detail / Detail by account / Mailboxes and aliases / Sources and checks,
  plus a summary on screen.
"""
